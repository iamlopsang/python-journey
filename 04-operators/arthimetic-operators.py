            ## ARITHEMATIC IN PYTHON ##

"""Arithmetic operators are used for mathematical calculations.

|Operator | Name           | Example   | Output  | Explanation                                                     |
|---      |---             |---        |---      |---                                                              |
| `+`     | Addition       | `10 + 3`  | `13`    | Adds two values.                                                |
| `-`     | Subtraction    | `10 - 3`  | `7`     | Subtracts the second value from the first.                      |
| `*`     | Multiplication | `10 * 3`  | `30`    | Multiplies two values.                                          |
| `/`     | Division       | `10 / 3`  | `3.33..`| Divides the first value by the second and returns a float.      |
| `%`     | Modulus        | `10 % 3`  | `1`     | Returns the remainder after division.                           |
| `**`    | Exponentiation | `10 ** 3` | `1000`  | Raises the first value to the power of the second.              |
| `//`    | Floor Division | `10 // 3` | `3`     | Divides and rounds the result down to the nearest whole number. |"""

## Addition in Arithmetic operators of Python:

x = 10
y = 5
print(x+y)  #Output: 15

## Subtraction in Arithmetic operators of Python:

x = 10
y = 5
print(x-y)  #Output: 5

## Multiplication in Arithmetic operators of Python:

x = 10
y = 5
print(x*y)  #Output: 50

## Division in Arithmetic operators of Python:

x = 10
y = 5
print(x/y)  #Output: 2

## Modulus in Arithmetic operators of Python:
"""Returns the remainder."""

x = 10
print(x % 3)    #Output: 1

## Exponential in Arithmetic operators of Python:
"""Raises a number to a power."""

x = 2**3
print(x)    #Output: 8

## Floor Division in Arithmetic operators of Python:
"""Returns the division result rounded down to the nearest whole number."""

x =  10//3
print(x)    #Output: 3




