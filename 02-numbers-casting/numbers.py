        ## Python Numbers ##

    ## Python has three main numeric types:
        # > int(integer)
        # > float
        # > complex

 ## Integer(int) type:

x = 10  # integer can be positive
y = -5  # integer can be negative
z = 0   # integer can be zero

 ## Float (float) type:

a = 3.14  # float can be positive
b = -2.5  # float can be negative   
c = 0.0   # float can be zero

 ## Scientific Notation:

d = 3e2   # 3 * 10^2
e = -4e3  # -4 * 10^3
f = 2.5e-1 # 2.5 * 10^-1

 ## Complex (complex) type:

x = 2 + 3j  # complex number with real and imaginary parts

    # 2 is real part and 3j is imaginary part

 ## Type Conversion (Casting) in Python:

x = 10
a = float(x)  # convert int to float
b = complex(x)  # convert int to complex

 ## Random Number Generation:

import random

print(random.randint(1, 100))  # generates a random integer between 1 and 100

