        ## Python Data Types ##

# String
name = "Alex"

# Integer
age = 25

# Float
height = 5.8

# Complex
number = 2 + 3j

# Boolean
is_student = True

# List
colors = ["red", "blue", "green"]

# Tuple
coordinates = (10, 20)

# Range
numbers = range(5)

# Dictionary
student = {"name": "Alex", "age": 25}

# Set
unique_numbers = {1, 2, 3}

# Frozen set
fixed_numbers = frozenset({1, 2, 3})

# Bytes
data = b"Hello"

# Byte array
mutable_data = bytearray(5)

# Memory view
view = memoryview(bytes(5))

# None type
result = None

# Checking data types
print(type(name))
print(type(age))
print(type(height))
print(type(is_student))
print(type(student))
print(type(result))

