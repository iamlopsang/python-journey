        ## PYTHON BOOLEAN ##

"""A Boolean represents one of two values:
    > True
    > False"""

# Example:

is_student = True
is_logged = False

##  Boolean Values from Comparisons:

x = 10
y = 5
print(x>y)  # Output -> True

print(x<y)  # Output -> False

## Boolean Values From Condition:
"""Conditions can also produce Boolean results."""

# Example:

age = 20
if age >= 18:
    print("Adult")

# Output -> Adult     

